#include <iostream>
using namespace std;

int main() {
    // Declarar una variable para guardar la entrada del usuario
    int edad;

    // Solicitar al usuario que introduzca su edad
    cout << "Por favor, introduce tu edad: ";

    // Leer la edad del usuario y guardarla en la variable 'edad'
    cin >> edad;

    // Mostrar un mensaje con la edad ingresada
    cout << "Tienes " << edad << " años." << endl;

    return 0;
}

