// Ejemplo cmath
#include <iostream>
using namespace std;
#include <cmath>

int main () {
double a=5.0, b=2.0;

cout << "El seno de " << a << " es " << sin(a) << endl;
cout << "La exponencial de " << b << " es " << exp(b) << endl;
cout << "El logaritmo neperiano de " << a << " es " << log(a) << endl;
cout << a << " elevado a " << b << " es " << pow(a,b) << endl;
cout << "La raíz cuadrada de " << b << " es " << sqrt(b) << endl;
cout << "El valor absoluto de " << a << " es " << fabs(a) << endl;
return 0;
}

